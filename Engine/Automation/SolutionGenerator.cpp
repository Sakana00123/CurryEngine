#include "SolutionGenerator.h"
#include <fstream>
#include <stdexcept>

namespace fs = std::filesystem;
namespace
{
    std::string Escape(const fs::path& path)
    {
        const auto utf8 = path.generic_u8string();
        std::string result;
        for (auto c : utf8)
        {
            switch (c)
            {
            case '&': result += "&amp;"; break;
            case '<': result += "&lt;"; break;
            case '>': result += "&gt;"; break;
            case '"': result += "&quot;"; break;
            case '\'': result += "&apos;"; break;
            case '%': result += "%25"; break;
            case '$': result += "%24"; break;
            case '@': result += "%40"; break;
            case ';': result += "%3B"; break;
            case '(': result += "%28"; break;
            case ')': result += "%29"; break;
            default: result += static_cast<char>(c); break;
            }
        }
        return result;
    }

    void CheckGenerated(const fs::path& path)
    {
        if (!fs::exists(path)) return;
        std::ifstream input(path, std::ios::binary);
        const std::string text{std::istreambuf_iterator<char>(input), std::istreambuf_iterator<char>()};
        if (!input || text.find("Generated by CurryEngine") == std::string::npos)
            throw std::runtime_error("Refusing to overwrite a non-generated solution/project file.");
    }

    void Write(const fs::path& path, const std::string& text)
    {
        std::ofstream output(path, std::ios::binary | std::ios::trunc);
        output << text;
        output.close();
        if (!output) throw std::runtime_error("Cannot write generated solution/project file.");
    }
}

void SolutionGenerator::Generate(const CurryEngine::ProjectContext& context)
{
    if (!context.IsExternalProject()) throw std::runtime_error("A project file is required.");
    const auto project = context.projectRoot / "Assembly-CSharp.csproj";
    auto solution = context.projectFile;
    solution.replace_extension(".sln");
    CheckGenerated(project);
    CheckGenerated(solution);
    for (const auto* dll : {"CurryEngine.Core", "CurryEngine.Runtime", "CurryEngine.API"})
        if (!fs::is_regular_file(context.engineRoot / (std::string(dll) + ".dll")))
            throw std::runtime_error(std::string("Missing engine reference: ") + dll);

    std::string csproj = R"(<Project>
  <!-- Generated by CurryEngine. Regenerated when opening the project. -->
  <PropertyGroup>
    <BaseIntermediateOutputPath>Library/obj/</BaseIntermediateOutputPath>
    <MSBuildProjectExtensionsPath>Library/obj/</MSBuildProjectExtensionsPath>
  </PropertyGroup>
  <Import Project="Sdk.props" Sdk="Microsoft.NET.Sdk" />
  <PropertyGroup>
    <TargetFramework>net9.0</TargetFramework>
    <AssemblyName>Assembly-CSharp</AssemblyName>
    <PlatformTarget>x64</PlatformTarget>
    <ImplicitUsings>enable</ImplicitUsings>
    <Nullable>enable</Nullable>
    <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
    <OutputPath>Library/ScriptAssemblies/</OutputPath>
    <AppendTargetFrameworkToOutputPath>false</AppendTargetFrameworkToOutputPath>
    <AppendRuntimeIdentifierToOutputPath>false</AppendRuntimeIdentifierToOutputPath>
    <DebugType>portable</DebugType>
  </PropertyGroup>
  <ItemGroup>
    <Compile Include="Assets/**/*.cs" Exclude="Assets/**/bin/**;Assets/**/obj/**" />
  </ItemGroup>
  <ItemGroup>
)";
    for (const auto* dll : {"CurryEngine.Core", "CurryEngine.Runtime", "CurryEngine.API"})
        csproj += "    <Reference Include=\"" + std::string(dll) + "\"><HintPath>" +
            Escape(context.engineRoot / (std::string(dll) + ".dll")) + "</HintPath><Private>false</Private></Reference>\n";
    csproj += "  </ItemGroup>\n  <Import Project=\"Sdk.targets\" Sdk=\"Microsoft.NET.Sdk\" />\n</Project>\n";
    const std::string guid = "{8A5B4A7C-1234-4321-ABCD-000000000001}";
    std::string sln = "\xEF\xBB\xBF\nMicrosoft Visual Studio Solution File, Format Version 12.00\n"
        "# Generated by CurryEngine\n# Visual Studio Version 17\n"
        "Project(\"{FAE04EC0-301F-11D3-BF4B-00C04F79EFBC}\") = \"Assembly-CSharp\", \"Assembly-CSharp.csproj\", \"" + guid + "\"\nEndProject\nGlobal\n"
        "\tGlobalSection(SolutionConfigurationPlatforms) = preSolution\n\t\tDebug|Any CPU = Debug|Any CPU\n\t\tRelease|Any CPU = Release|Any CPU\n\tEndGlobalSection\n"
        "\tGlobalSection(ProjectConfigurationPlatforms) = postSolution\n";
    for (const auto* config : {"Debug", "Release"})
        for (const auto* key : {"ActiveCfg", "Build.0"})
            sln += "\t\t" + guid + "." + config + "|Any CPU." + key + " = " + config + "|Any CPU\n";
    sln += "\tEndGlobalSection\nEndGlobal\n";
    Write(project, csproj);
    Write(solution, sln);
}
